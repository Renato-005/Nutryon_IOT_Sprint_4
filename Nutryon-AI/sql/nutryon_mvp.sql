-- ============================================================
-- BLOCO 15 – VIEW: DASHBOARD DO USUÁRIO
-- Consumo do dia vs meta calórica
-- ============================================================

CREATE OR REPLACE VIEW VW_DASHBOARD_USUARIO AS
SELECT
    u.ID_USUARIO,
    u.NOM_USUARIO,
    u.OBJETIVO,
    u.META_KCAL,
    ROUND(NVL(SUM(i.KCAL_100G * ri.QTDE_G / 100), 0))                                   AS KCAL_CONSUMIDA,
    ROUND(u.META_KCAL - NVL(SUM(i.KCAL_100G * ri.QTDE_G / 100), 0))                     AS KCAL_RESTANTE,
    ROUND(NVL(SUM(i.PROT_100G * ri.QTDE_G / 100), 0), 1)                                 AS PROT_CONSUMIDA,
    ROUND(NVL(SUM(i.CARB_100G * ri.QTDE_G / 100), 0), 1)                                 AS CARB_CONSUMIDA,
    ROUND(NVL(SUM(i.GORD_100G * ri.QTDE_G / 100), 0), 1)                                 AS GORD_CONSUMIDA,
    ROUND(NVL(SUM(i.KCAL_100G * ri.QTDE_G / 100), 0) / NULLIF(u.META_KCAL,0) * 100, 1)  AS PCT_META
FROM USUARIO u
LEFT JOIN REFEICAO r
    ON r.ID_USUARIO = u.ID_USUARIO
    AND TRUNC(r.DT_REF) = TRUNC(SYSDATE)
LEFT JOIN REFEICAO_ITEM ri ON ri.ID_REFEICAO   = r.ID_REFEICAO
LEFT JOIN INGREDIENTE   i  ON i.ID_INGREDIENTE = ri.ID_INGREDIENTE
GROUP BY u.ID_USUARIO, u.NOM_USUARIO, u.OBJETIVO, u.META_KCAL


-- ============================================================
-- BLOCO 16 – VIEW: HISTÓRICO DE REFEIÇÕES
-- Todas as refeições com macros calculados automaticamente
-- ============================================================

CREATE OR REPLACE VIEW VW_HISTORICO_REFEICOES AS
SELECT
    u.NOM_USUARIO,
    t.NOM_TIPO                                   AS TIPO_REFEICAO,
    TO_CHAR(r.DT_REF, 'DD/MM/YYYY HH24:MI')      AS DATA_HORA,
    i.NOM_INGREDIENTE,
    ri.QTDE_G                                    AS QUANTIDADE_G,
    ROUND(i.KCAL_100G * ri.QTDE_G / 100, 1)      AS KCAL,
    ROUND(i.PROT_100G * ri.QTDE_G / 100, 1)      AS PROTEINA_G,
    ROUND(i.CARB_100G * ri.QTDE_G / 100, 1)      AS CARBO_G,
    ROUND(i.GORD_100G * ri.QTDE_G / 100, 1)      AS GORDURA_G,
    r.OBS
FROM REFEICAO r
JOIN USUARIO       u  ON u.ID_USUARIO       = r.ID_USUARIO
JOIN TIPO_REFEICAO t  ON t.ID_TIPO_REFEICAO = r.ID_TIPO_REFEICAO
JOIN REFEICAO_ITEM ri ON ri.ID_REFEICAO     = r.ID_REFEICAO
JOIN INGREDIENTE   i  ON i.ID_INGREDIENTE   = ri.ID_INGREDIENTE
ORDER BY r.DT_REF DESC


-- ============================================================
-- BLOCO 17 – VIEW: SUGESTÕES IA
-- Ingredientes mais frequentes por tipo de refeição
-- com percentual de confiança calculado por SQL analítico
-- ============================================================

CREATE OR REPLACE VIEW VW_SUGESTOES_REFEICAO AS
SELECT
    t.NOM_TIPO                                                                 AS TIPO_REFEICAO,
    i.NOM_INGREDIENTE                                                          AS ALIMENTO_SUGERIDO,
    COUNT(*)                                                                   AS FREQUENCIA,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (PARTITION BY t.NOM_TIPO), 1) AS CONFIANCA_PCT,
    i.KCAL_100G,
    i.PROT_100G                                                                AS PROTEINAS_100G,
    i.CARB_100G                                                                AS CARBOIDRATOS_100G,
    i.GORD_100G                                                                AS GORDURAS_100G
FROM REFEICAO r
JOIN TIPO_REFEICAO t  ON t.ID_TIPO_REFEICAO = r.ID_TIPO_REFEICAO
JOIN REFEICAO_ITEM ri ON ri.ID_REFEICAO     = r.ID_REFEICAO
JOIN INGREDIENTE   i  ON i.ID_INGREDIENTE   = ri.ID_INGREDIENTE
GROUP BY t.NOM_TIPO, i.NOM_INGREDIENTE,
         i.KCAL_100G, i.PROT_100G, i.CARB_100G, i.GORD_100G
ORDER BY t.NOM_TIPO, FREQUENCIA DESC


