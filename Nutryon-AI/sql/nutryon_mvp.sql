-- ============================================================
-- BLOCO 5 – CRIAR TABELA INGREDIENTE
-- Macros incorporados diretamente (kcal, proteína, carbo, gordura por 100g)
-- ============================================================

CREATE TABLE INGREDIENTE (
    ID_INGREDIENTE  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOM_INGREDIENTE VARCHAR2(120) NOT NULL UNIQUE,
    ID_CATEGORIA    NUMBER REFERENCES CATEGORIA_INGREDIENTE(ID_CATEGORIA),
    KCAL_100G       NUMBER DEFAULT 0,
    PROT_100G       NUMBER DEFAULT 0,
    CARB_100G       NUMBER DEFAULT 0,
    GORD_100G       NUMBER DEFAULT 0
)


-- ============================================================
-- BLOCO 6 – CRIAR TABELA REFEICAO
-- ============================================================

CREATE TABLE REFEICAO (
    ID_REFEICAO      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO       NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
    DT_REF           DATE NOT NULL,
    ID_TIPO_REFEICAO NUMBER NOT NULL REFERENCES TIPO_REFEICAO(ID_TIPO_REFEICAO),
    OBS              VARCHAR2(200)
)


-- ============================================================
-- BLOCO 7 – CRIAR TABELA REFEICAO_ITEM
-- ============================================================

CREATE TABLE REFEICAO_ITEM (
    ID_ITEM        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_REFEICAO    NUMBER NOT NULL REFERENCES REFEICAO(ID_REFEICAO) ON DELETE CASCADE,
    ID_INGREDIENTE NUMBER NOT NULL REFERENCES INGREDIENTE(ID_INGREDIENTE),
    QTDE_G         NUMBER NOT NULL
)


