CREATE OR REPLACE FUNCTION FUN_REFEICAO_JSON (
    p_id_refeicao NUMBER
) RETURN CLOB
IS
    v_json CLOB := '';
BEGIN
    FOR rec IN (
        SELECT r.ID_REFEICAO,
               u.NOM_USUARIO,
               t.NOM_TIPO,
               r.DT_REF
        FROM REFEICAO r
        JOIN USUARIO u ON u.ID_USUARIO = r.ID_USUARIO
        JOIN TIPO_REFEICAO t ON t.ID_TIPO_REFEICAO = r.ID_TIPO_REFEICAO
        WHERE r.ID_REFEICAO = p_id_refeicao
    )
    LOOP
        v_json := '{' ||
                  '"id_refeicao": ' || rec.ID_REFEICAO || ',' ||
                  '"usuario": "' || rec.NOM_USUARIO || '",' ||
                  '"tipo": "' || rec.NOM_TIPO || '",' ||
                  '"data": "' || TO_CHAR(rec.DT_REF, 'YYYY-MM-DD') || '"' ||
                  '}';
    END LOOP;
 
    RETURN v_json;
 
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Erro: Refeição não encontrada';
    WHEN OTHERS THEN
        RETURN 'Erro inesperado';
END;
/
 

