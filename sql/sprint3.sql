CREATE OR REPLACE PROCEDURE PRC_RELATORIO_REFEICOES_JSON (
    p_id_usuario IN NUMBER
) AS
    v_json CLOB;
    v_count NUMBER;
    v_usuario VARCHAR2(100);
BEGIN
    IF p_id_usuario IS NULL THEN
        RAISE_APPLICATION_ERROR(-20501, 'ID do usuario e obrigatorio');
    END IF;
 
    SELECT COUNT(*) INTO v_count FROM USUARIO WHERE ID_USUARIO = p_id_usuario;
    IF v_count = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;
 
    SELECT NOM_USUARIO INTO v_usuario FROM USUARIO WHERE ID_USUARIO = p_id_usuario;
 
    DBMS_OUTPUT.PUT_LINE('Refeicoes do usuario: ' || v_usuario);
    DBMS_OUTPUT.PUT_LINE('----------------------------------------');
 
    v_count := 0;
    FOR rec IN (
        SELECT r.ID_REFEICAO
          FROM REFEICAO r
          JOIN USUARIO u ON u.ID_USUARIO = r.ID_USUARIO
          JOIN TIPO_REFEICAO t ON t.ID_TIPO_REFEICAO = r.ID_TIPO_REFEICAO
         WHERE r.ID_USUARIO = p_id_usuario
         ORDER BY r.DT_REF
    ) LOOP
        v_json := FUN_REFEICAO_JSON(rec.ID_REFEICAO);
        DBMS_OUTPUT.PUT_LINE(v_json);
        v_count := v_count + 1;
    END LOOP;
 
    IF v_count = 0 THEN
        DBMS_OUTPUT.PUT_LINE('Nenhuma refeicao encontrada para este usuario.');
    END IF;
 
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Erro: Usuario nao encontrado.');
    WHEN VALUE_ERROR THEN
        DBMS_OUTPUT.PUT_LINE('Erro: Valor invalido informado.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Erro inesperado: ' || SQLERRM);
END;
/
 

CREATE OR REPLACE PROCEDURE PRC_NUTRIENTES_ANTERIOR_PROXIMO AS
    TYPE t_id_ing IS TABLE OF NUMBER;
    TYPE t_id_nut IS TABLE OF NUMBER;
    TYPE t_valor IS TABLE OF NUMBER;
    
    v_ids_ing t_id_ing;
    v_ids_nut t_id_nut;
    v_valores t_valor;
    v_anterior VARCHAR2(20);
    v_proximo VARCHAR2(20);
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM INGREDIENTE_NUTRIENTE;
    
    IF v_count = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;
 
    SELECT ID_INGREDIENTE, ID_NUTRIENTE, VALOR_POR_BASE
      BULK COLLECT INTO v_ids_ing, v_ids_nut, v_valores
      FROM INGREDIENTE_NUTRIENTE
     ORDER BY ID_INGREDIENTE, ID_NUTRIENTE;
 
    DBMS_OUTPUT.PUT_LINE(RPAD('INGREDIENTE',15) || RPAD('NUTRIENTE',15) || RPAD('ANTERIOR',15) || RPAD('ATUAL',15) || RPAD('PROXIMO',15));
    DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');
 
    FOR i IN 1..v_valores.COUNT LOOP
        IF i = 1 THEN
            v_anterior := 'Vazio';
        ELSE
            v_anterior := TO_CHAR(v_valores(i-1));
        END IF;
 
        IF i = v_valores.COUNT THEN
            v_proximo := 'Vazio';
        ELSE
            v_proximo := TO_CHAR(v_valores(i+1));
        END IF;
 
        DBMS_OUTPUT.PUT_LINE(
            RPAD(v_ids_ing(i),15) ||
            RPAD(v_ids_nut(i),15) ||
            RPAD(v_anterior,15) ||
            RPAD(TO_CHAR(v_valores(i)),15) ||
            RPAD(v_proximo,15)
        );
    END LOOP;
 
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Erro: Nenhum registro encontrado.');
    WHEN VALUE_ERROR THEN
        DBMS_OUTPUT.PUT_LINE('Erro: Problema na conversao de valores.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Erro inesperado: ' || SQLERRM);
END;
/
 

CREATE OR REPLACE FUNCTION FUN_CALC_CALORIAS_REFEICAO (
    p_id_refeicao NUMBER
) RETURN NUMBER
IS
    v_total NUMBER := 0;
    v_count NUMBER;
BEGIN
    IF p_id_refeicao IS NULL THEN
        RAISE_APPLICATION_ERROR(-20601, 'ID da refeicao e obrigatorio');
    END IF;
 
    SELECT COUNT(*) INTO v_count FROM REFEICAO WHERE ID_REFEICAO = p_id_refeicao;
    IF v_count = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;
 
    SELECT NVL(SUM((ri.QTDE / inut.BASE_QTD) * inut.VALOR_POR_BASE), 0)
      INTO v_total
      FROM REFEICAO_ITEM ri
      JOIN INGREDIENTE_NUTRIENTE inut ON inut.ID_INGREDIENTE = ri.ID_INGREDIENTE
                                     AND inut.ID_UNIDADE_BASE = ri.ID_UNIDADE
      JOIN NUTRIENTE n ON n.ID_NUTRIENTE = inut.ID_NUTRIENTE
     WHERE ri.ID_REFEICAO = p_id_refeicao
       AND n.NOM_NUTRIENTE = 'CALORIA';
 
    RETURN ROUND(v_total, 2);
 
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1;
    WHEN VALUE_ERROR THEN
        RETURN -2;
    WHEN OTHERS THEN
        RETURN -99;
END;
/
 

CREATE TABLE AUDITORIA_INGREDIENTE (
    ID_AUDITORIA    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    OPERACAO        VARCHAR2(10) NOT NULL,
    USUARIO_BD      VARCHAR2(100) NOT NULL,
    DT_OPERACAO     DATE DEFAULT SYSDATE NOT NULL,
    OLD_ID          NUMBER,
    OLD_NOME        VARCHAR2(120),
    OLD_CATEGORIA   NUMBER,
    NEW_ID          NUMBER,
    NEW_NOME        VARCHAR2(120),
    NEW_CATEGORIA   NUMBER,
    CONSTRAINT PK_AUDITORIA_ING PRIMARY KEY (ID_AUDITORIA)
);
 
 
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_INGREDIENTE
AFTER INSERT OR UPDATE OR DELETE ON INGREDIENTE
FOR EACH ROW
DECLARE
    v_operacao VARCHAR2(10);
BEGIN
    IF INSERTING THEN
        v_operacao := 'INSERT';
    ELSIF UPDATING THEN
        v_operacao := 'UPDATE';
    ELSE
        v_operacao := 'DELETE';
    END IF;
 
    INSERT INTO AUDITORIA_INGREDIENTE (
        OPERACAO, USUARIO_BD, DT_OPERACAO,
        OLD_ID, OLD_NOME, OLD_CATEGORIA,
        NEW_ID, NEW_NOME, NEW_CATEGORIA
    ) VALUES (
        v_operacao, USER, SYSDATE,
        :OLD.ID_INGREDIENTE, :OLD.NOM_INGREDIENTE, :OLD.ID_CATEGORIA,
        :NEW.ID_INGREDIENTE, :NEW.NOM_INGREDIENTE, :NEW.ID_CATEGORIA
    );
END;
